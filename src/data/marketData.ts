// Helper to generate simulated candlestick series for any asset and timeframe
export function generateCandles(asset: MarketAsset, timeframe: string): CandleData[] {
  const count = timeframe === '1D' ? 36 : timeframe === '5D' ? 40 : timeframe === '1M' ? 30 : 50;
  const candles: CandleData[] = [];
  const basePrice = asset.price;
  const isUp = asset.changePercent >= 0;
  
  // Starting point relative to current price
  const startRatio = isUp ? 0.94 : 1.06;
  let current = basePrice * startRatio;
  
  const stepRatio = (basePrice - current) / count;
  const volatility = basePrice * 0.009;

  const now = new Date();

  for (let i = 0; i < count; i++) {
    const trendStep = current + stepRatio;
    const randomDelta = (Math.random() - 0.48) * volatility;
    const open = i === 0 ? current : candles[i - 1].close;
    let close = i === count - 1 ? basePrice : open + (trendStep - current) + randomDelta;
    
    // Bounds check
    const high = Math.max(open, close) + Math.random() * volatility * 0.7;
    const low = Math.min(open, close) - Math.random() * volatility * 0.7;
    current = close;

    let timeLabel = '';
    if (timeframe === '1D') {
      const minutes = 9 * 60 + 30 + i * 10;
      const hh = Math.floor(minutes / 60);
      const mm = minutes % 60;
      timeLabel = `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}`;
    } else if (timeframe === '5D') {
      const d = new Date(now.getTime() - (count - i) * 3 * 3600 * 1000);
      timeLabel = `${d.getMonth() + 1}/${d.getDate()} ${d.getHours()}:00`;
    } else {
      const d = new Date(now.getTime() - (count - i) * 24 * 3600 * 1000);
      const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
      timeLabel = `${months[d.getMonth()]} ${d.getDate()}`;
    }

    candles.push({
      time: timeLabel,
      open: Number(open.toFixed(asset.category === 'forex' ? 4 : asset.category === 'bonds' ? 3 : 2)),
      high: Number(high.toFixed(asset.category === 'forex' ? 4 : asset.category === 'bonds' ? 3 : 2)),
      low: Number(low.toFixed(asset.category === 'forex' ? 4 : asset.category === 'bonds' ? 3 : 2)),
      close: Number(close.toFixed(asset.category === 'forex' ? 4 : asset.category === 'bonds' ? 3 : 2)),
      volume: Math.floor(Math.random() * 500000 + 100000)
    });
  }

  return candles;
}
